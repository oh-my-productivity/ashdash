//! The pure decision "should this pasteboard change be recorded?".
//!
//! Kept free of any OS call so it can be unit-tested exhaustively; the
//! watcher (`crates/app/src/clipboard_watch.rs`) only gathers the inputs.
//!
//! Password managers and similar tools follow the <http://nspasteboard.org>
//! convention: they add a marker type to the pasteboard next to the real
//! content. Entries carrying such a marker must never reach the history.

/// Content the user wants kept secret (password managers).
pub const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";
/// Content that is only meant to live for a moment (e.g. one-time codes).
pub const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";
/// Content a program placed on the pasteboard without a user action.
pub const AUTO_GENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";

/// Every marker type that suppresses recording.
pub const SKIP_TYPES: [&str; 3] = [CONCEALED_TYPE, TRANSIENT_TYPE, AUTO_GENERATED_TYPE];

/// Bundle ids of password managers / keychain tools. Suggested default for the
/// per-app ignore list (the history itself starts with an empty list so that
/// tests and library users get no surprises). Unknown ids are harmless.
pub const DEFAULT_IGNORED_APPS: [&str; 6] = [
    "com.1password.1password",
    "com.agilebits.onepassword7",
    "com.bitwarden.desktop",
    "org.keepassxc.keepassxc",
    "com.apple.keychainaccess",
    "com.apple.Passwords",
];

/// Why a pasteboard change was not recorded.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SkipReason {
    /// The pasteboard carries one of [`SKIP_TYPES`].
    MarkerType(String),
    /// The frontmost application is on the ignore list.
    IgnoredApp(String),
    /// Ashdash put this text there itself (snippet auto-paste): it is not something the user copied.
    OwnPaste,
}

/// Decide whether a pasteboard change may be recorded, and if not, why.
///
/// * `types` - the pasteboard's type identifiers (UTIs).
/// * `frontmost_app` - bundle id of the frontmost application, if known.
///   When it is unknown the per-app list cannot apply and the entry is allowed.
/// * `ignore_list` - bundle ids to ignore; compared case-insensitively
///   (bundle ids are case-insensitive in practice), surrounding whitespace and
///   blank entries are ignored.
pub fn skip_reason<T: AsRef<str>>(
    types: &[T],
    frontmost_app: Option<&str>,
    ignore_list: &[String],
) -> Option<SkipReason> {
    for t in types {
        let t = t.as_ref();
        if SKIP_TYPES.iter().any(|s| s.eq_ignore_ascii_case(t)) {
            return Some(SkipReason::MarkerType(t.to_string()));
        }
    }
    let app = frontmost_app?.trim();
    if !app.is_empty()
        && ignore_list
            .iter()
            .map(|a| a.trim())
            .any(|a| !a.is_empty() && a.eq_ignore_ascii_case(app))
    {
        return Some(SkipReason::IgnoredApp(app.to_string()));
    }
    None
}

/// `true` when the change should be recorded. See [`skip_reason`].
pub fn should_record<T: AsRef<str>>(types: &[T], frontmost_app: Option<&str>, ignore_list: &[String]) -> bool {
    skip_reason(types, frontmost_app, ignore_list).is_none()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ignore(v: &[&str]) -> Vec<String> {
        v.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn plain_text_is_recorded() {
        assert!(should_record(
            &["public.utf8-plain-text", "NSStringPboardType"],
            Some("com.apple.Safari"),
            &[]
        ));
        assert!(should_record::<&str>(&[], None, &[]));
    }

    #[test]
    fn each_marker_type_blocks_recording() {
        for marker in SKIP_TYPES {
            let types = ["public.utf8-plain-text", marker];
            assert_eq!(
                skip_reason(&types, Some("com.apple.Safari"), &[]),
                Some(SkipReason::MarkerType(marker.to_string())),
                "{marker}"
            );
            assert!(!should_record(&types, None, &[]));
        }
    }

    #[test]
    fn marker_check_is_case_insensitive_and_exact() {
        assert!(!should_record(&["ORG.NSPASTEBOARD.CONCEALEDTYPE"], None, &[]));
        // Look-alikes are not markers.
        assert!(should_record(
            &["org.nspasteboard.ConcealedType.x", "org.nspasteboard"],
            None,
            &[]
        ));
    }

    #[test]
    fn ignored_app_blocks_recording() {
        let list = ignore(&["com.1password.1password"]);
        assert_eq!(
            skip_reason(&["public.utf8-plain-text"], Some("com.1password.1password"), &list),
            Some(SkipReason::IgnoredApp("com.1password.1password".into()))
        );
        assert!(should_record(
            &["public.utf8-plain-text"],
            Some("com.apple.Safari"),
            &list
        ));
    }

    #[test]
    fn ignore_list_matching_is_forgiving() {
        let list = ignore(&["  Com.Bitwarden.Desktop ", "", "   "]);
        assert!(!should_record(&["t"], Some("com.bitwarden.desktop"), &list));
        // Blank list entries never match an empty/unknown app.
        assert!(should_record(&["t"], Some(""), &list));
        assert!(should_record(&["t"], None, &list));
    }

    #[test]
    fn unknown_frontmost_app_cannot_be_ignored() {
        assert!(should_record(&["t"], None, &ignore(&["com.x"])));
    }

    #[test]
    fn marker_wins_over_allowed_app() {
        assert!(!should_record(
            &[TRANSIENT_TYPE],
            Some("com.apple.Safari"),
            &ignore(&["com.other"])
        ));
    }

    #[test]
    fn default_ignore_list_has_no_blanks() {
        assert!(
            DEFAULT_IGNORED_APPS
                .iter()
                .all(|a| !a.trim().is_empty() && a.contains('.'))
        );
    }
}
