#!/usr/bin/env python3
"""Regenerate NOTICE: the third-party licences of everything that ships in the app.

    scripts/gen-notice.py            rewrite NOTICE
    scripts/gen-notice.py --check    exit 1 when NOTICE is out of date (for CI)

Source of truth is `cargo metadata --locked` for the two macOS targets we build
(aarch64 + x86_64), following normal and build dependencies only: dev-dependencies
(criterion, proptest) and crates that only other platforms use are not shipped
and are not listed. No dependency is added to the project; only python3 and cargo
are needed. The licence column is the SPDX expression each crate declares;
this script does not read licence texts.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin"]

HEADER = """\
Ashdash
Copyright (c) 2026 the Ashdash contributors

Ashdash is licensed under either of

  * the MIT license (LICENSE-MIT), or
  * the Apache License, Version 2.0 (LICENSE-APACHE),

at your option (SPDX: MIT OR Apache-2.0).

Ashdash is an independent, original implementation. Apart from the open source
dependencies listed below, it contains no third-party code or assets.

This product includes software developed by third parties. The list below is
generated by scripts/gen-notice.py from Cargo.lock; do not edit it by hand.

Fonts
-----
The launcher window embeds the default fonts of the egui crate family
(crate epaint_default_fonts), which are licensed separately from the Rust code:

  * Hack Regular (MIT; derived from Bitstream Vera and DejaVu, Bitstream Vera License)
  * Ubuntu-Light (Ubuntu Font Licence 1.0)
  * Noto Emoji Regular (SIL Open Font License 1.1)
  * emoji-icon-font (MIT, Copyright (c) 2014 John Slegers)

The licence texts are part of the epaint_default_fonts source package
(crates.io, directory `fonts/`). A binary distribution must keep this notice.

The preferences window additionally embeds three static font files
(crates/app/resources/fonts/, sources and checksums in SOURCES.md), both families
under the SIL Open Font License 1.1; the licence texts are shipped next to the files:

  * Inter Regular and Inter Medium 4.1
    (Copyright (c) 2016 The Inter Project Authors, https://github.com/rsms/inter)
  * Geist Mono Regular 1.8.1
    (Copyright 2024 The Geist Project Authors, https://github.com/vercel/geist-font)

Rust crates
-----------
Format: name version - SPDX licence expression - source
"""


def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def shipped(meta):
    """Packages reachable from the workspace through normal/build dependencies."""
    pk = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    ws = set(meta["workspace_members"])
    seen, stack = set(), list(ws)
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if all(k["kind"] == "dev" for k in d["dep_kinds"]):
                continue
            stack.append(d["pkg"])
    return {(pk[i]["name"], pk[i]["version"]): pk[i] for i in seen if i not in ws}


def render():
    pkgs = {}
    for t in TARGETS:
        pkgs.update(shipped(metadata(t)))
    lines = [HEADER]
    for (name, version), p in sorted(pkgs.items()):
        lic = p.get("license") or ("(see " + p["license_file"] + ")" if p.get("license_file") else "UNKNOWN")
        src = p.get("repository") or p.get("homepage") or "https://crates.io/crates/" + name
        lines.append(f"{name} {version} - {lic} - {src}\n")
    return "".join(lines)


def main():
    text = render()
    notice = ROOT / "NOTICE"
    if "--check" in sys.argv:
        if not notice.exists() or notice.read_text() != text:
            print("NOTICE is out of date: run scripts/gen-notice.py", file=sys.stderr)
            sys.exit(1)
        print("NOTICE is up to date")
        return
    notice.write_text(text)
    print(f"wrote {notice} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
